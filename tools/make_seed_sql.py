"""Writes database/seed.sql (INSERT statements) from data/sudar-data.json.
Run from the tools folder:  python3 make_seed_sql.py
Use it if you prefer loading MySQL Workbench / the mysql client instead of the Java import."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, '..', 'data', 'sudar-data.json'), encoding='utf-8'))
q = lambda s: "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"
out = ["-- Generated by tools/make_seed_sql.py from data/sudar-data.json", "USE sudar_dispatch;", "SET FOREIGN_KEY_CHECKS=0;",
       "DELETE FROM dispatch_log; DELETE FROM assignments; DELETE FROM incident_needs; DELETE FROM incidents; DELETE FROM roads; DELETE FROM units; DELETE FROM locations;",
       "SET FOREIGN_KEY_CHECKS=1;"]
for i, l in enumerate(d['locations']):
    out.append(f"INSERT INTO locations(id,seq,name,type,lat,lon,taluk,x,y) VALUES ({q(l['id'])},{i},{q(l['name'])},{q(l['type'])},{l['lat']},{l['lon']},{q(l['taluk'])},{l['x']},{l['y']});")
for r in d['roads']:
    out.append(f"INSERT INTO roads(from_id,to_id,km,traffic,blocked) VALUES ({q(r['from'])},{q(r['to'])},{r['km']},{r['traffic']},{1 if r['blocked'] else 0});")
for i, u in enumerate(d['units']):
    out.append(f"INSERT INTO units(id,seq,type,station) VALUES ({q(u['id'])},{i},{q(u['type'])},{q(u['station'])});")
for inc in d['incidents']:
    out.append(f"INSERT INTO incidents(id,type,location,severity,reported_at,status) VALUES ({q(inc['id'])},{q(inc['type'])},{q(inc['location'])},{inc['severity']},{inc['reportedAt']},'PENDING');")
    for n, need in enumerate(inc['needs']):
        out.append(f"INSERT INTO incident_needs(incident_id,seq,need) VALUES ({q(inc['id'])},{n},{q(need)});")
path = os.path.join(here, '..', 'database', 'seed.sql')
open(path, 'w', encoding='utf-8').write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), len(out), "statements")
